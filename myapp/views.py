def base_context(active="home"):
    return {
        "nav_items": NAV_ITEMS,
        "active": active,
        "asset": ASSET,
        "student_pathway": STUDENT_PATHWAY,
        "quick_links": [
            ("admission", "Поступление"),
            ("programs", "Направления"),
            ("contacts", "Контакты"),
        ],
    }


def home(request):
    context = base_context("home")
    context.update(
        {
            "programs": PROGRAMS,
            "future_programs": FUTURE_PROGRAMS,
            "opportunities": OPPORTUNITIES,
            "partners": PARTNERS,
            "news_items": NEWS_ITEMS,
            "history": HISTORY_MILESTONES,
        }
    )
    return render(request, "myapp/home.html", context)


def page(request, slug):
    try:
        page_data = PAGES[slug]
    except KeyError as exc:
        raise Http404("Page not found") from exc
    context = base_context(slug)
    context["page"] = page_data
    return render(request, "myapp/page.html", context)
